"""
Service: generate_schema_docs.py
Purpose: Generates a comprehensive, human-readable Markdown document (documentation/DATABASE_SCHEMA.md)
         detailing table schemas, column types, primary keys, descriptions, total record counts,
         latest synchronization timestamps, and sample records across all master SQLite catalogs.
"""

import os
import sqlite3
from datetime import datetime
from typing import Dict, List, Optional, Tuple

DOCS_DIR = "documentation"
OUTPUT_MD_PATH = os.path.join(DOCS_DIR, "DATABASE_SCHEMA.md")

DATABASES = [
    {
        "name": "Mutual Funds Catalog",
        "file": os.path.join("data", "master_mutual_funds.sqlite"),
        "tables": ["master_mutual_funds"]
    },
    {
        "name": "Equities, ETFs & SGBs Catalog",
        "file": os.path.join("data", "master_equities_etfs.sqlite"),
        "tables": ["master_equities_etfs"]
    },
    {
        "name": "Insurers & ULIP SFIN Catalog",
        "file": os.path.join("data", "master_insurers_ulips.sqlite"),
        "tables": ["master_insurers", "master_ulip_funds"]
    }
]

def get_table_metadata(cursor: sqlite3.Cursor, table_name: str) -> List[Tuple[str, str, int, str]]:
    """Fetches schema column definitions from _schema_documentation or falls back to PRAGMA table_info."""
    try:
        cursor.execute("""
            SELECT column_name, data_type, is_primary_key, description
            FROM _schema_documentation
            WHERE table_name = ?
            ORDER BY is_primary_key DESC, column_name ASC
        """, (table_name,))
        rows = cursor.fetchall()
        if rows:
            return rows
    except sqlite3.OperationalError:
        pass

    # Fallback to standard PRAGMA if documentation table is absent
    cursor.execute(f"PRAGMA table_info({table_name})")
    pragma_rows = cursor.fetchall()
    return [(row[1], row[2], row[5], "Standard schema attribute") for row in pragma_rows]

def get_table_statistics(cursor: sqlite3.Cursor, table_name: str) -> Tuple[int, Optional[str], Optional[str]]:
    """Calculates record count, latest sync timestamp, and active status count."""
    cursor.execute(f"SELECT COUNT(*) FROM {table_name}")
    count = cursor.fetchone()[0]

    # Query latest updated_at timestamp if present
    latest_update = None
    try:
        cursor.execute(f"SELECT MAX(updated_at) FROM {table_name}")
        val = cursor.fetchone()[0]
        if val:
            latest_update = val
    except sqlite3.OperationalError:
        pass

    # Query active status count if status column exists
    active_count = None
    try:
        cursor.execute(f"SELECT COUNT(*) FROM {table_name} WHERE status = 'ACTIVE'")
        active_count = cursor.fetchone()[0]
    except sqlite3.OperationalError:
        pass

    return count, latest_update, active_count

def get_sample_record(cursor: sqlite3.Cursor, table_name: str) -> Optional[Dict]:
    """Retrieves one sample row formatted as dictionary."""
    cursor.execute(f"SELECT * FROM {table_name} LIMIT 1")
    row = cursor.fetchone()
    if row:
        col_names = [description[0] for description in cursor.description]
        return dict(zip(col_names, row))
    return None

def build_markdown() -> str:
    now_utc = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")
    lines = [
        "# Database Schema & Catalog Health Report",
        "",
        f"> **Automated Documentation** | Generated on `{now_utc}`",
        "",
        "This file is automatically generated after every sync pipeline run. It provides technical specifications for database tables, column types, live entity counts, and integration guidelines for client applications.",
        "",
        "---",
        "",
        "## Summary Overview",
        "",
        "| Database | Table Name | Total Records | Active Units | Last Synced (UTC) | File Size |",
        "| :--- | :--- | :--- | :--- | :--- | :--- |"
    ]

    # Populate Summary Overview Table
    for db in DATABASES:
        db_path = db["file"]
        if not os.path.exists(db_path):
            for tbl in db["tables"]:
                lines.append(f"| {db['name']} | `{tbl}` | *Missing* | *N/A* | *N/A* | 0 KB |")
            continue

        file_size_kb = round(os.path.getsize(db_path) / 1024, 2)
        conn = sqlite3.connect(db_path)
        cur = conn.cursor()

        for tbl in db["tables"]:
            count, latest_update, active_cnt = get_table_statistics(cur, tbl)
            sync_str = f"`{latest_update}`" if latest_update else "*N/A*"
            active_str = f"{active_cnt:,}" if active_cnt is not None else "*N/A*"
            lines.append(f"| {db['name']} | `{tbl}` | {count:,} | {active_str} | {sync_str} | {file_size_kb:,} KB |")

        conn.close()

    lines.extend(["", "---", ""])

    # Detailed Table Specifications
    for db in DATABASES:
        db_path = db["file"]
        lines.append(f"## {db['name']}")
        lines.append(f"- **Local SQLite File:** `{db['file']}`")

        if not os.path.exists(db_path):
            lines.append("- **Status:** ⚠️ *Database file not generated yet.*\n")
            continue

        conn = sqlite3.connect(db_path)
        cur = conn.cursor()

        for tbl in db["tables"]:
            count, latest_update, active_cnt = get_table_statistics(cur, tbl)
            columns = get_table_metadata(cur, tbl)
            sample = get_sample_record(cur, tbl)

            lines.extend([
                f"",
                f"### Table: `{tbl}`",
                f"- **Total Rows:** `{count:,}`",
                f"- **Active Records:** `{active_cnt if active_cnt is not None else 'N/A'}`",
                f"- **Last Updated:** `{latest_update if latest_update else 'N/A'}`",
                f"",
                f"#### Column Definitions",
                f"",
                f"| Column | Type | Primary Key | Description |",
                f"| :--- | :--- | :---: | :--- |"
            ])

            for col_name, data_type, is_pk, description in columns:
                pk_indicator = "✅ Yes" if is_pk else "No"
                lines.append(f"| `{col_name}` | `{data_type}` | {pk_indicator} | {description} |")

            if sample:
                lines.extend([
                    f"",
                    f"#### Sample Record",
                    f"```json"
                ])
                import json
                lines.append(json.dumps(sample, indent=2, default=str))
                lines.append("```")

        conn.close()
        lines.extend(["", "---", ""])

    return "\n".join(lines)

def run():
    os.makedirs(DOCS_DIR, exist_ok=True)
    md_content = build_markdown()
    with open(OUTPUT_MD_PATH, "w", encoding="utf-8") as f:
        f.write(md_content)
    print(f"[Documentation Engine] Successfully updated {OUTPUT_MD_PATH}")

if __name__ == "__main__":
    run()